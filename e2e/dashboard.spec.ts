import { test, expect } from '@playwright/test';

// Playwright starts an isolated API on 3002 with in-memory SQLite and a separate
// Vite frontend on 5174. Tests never modify operator data or open serial ports.
test('full demo workflow, live updates, search focus, details, export, reset and responsive layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByText('System operational')).toBeVisible();
  await expect(page.getByText('Ready for the first arrival')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Waiting for reader' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/dashboard-empty.png', fullPage: true });
  await page.getByRole('checkbox', { name: 'Demo mode' }).click();
  await expect(page.getByRole('checkbox', { name: 'Demo mode' })).toBeChecked();
  await expect(page.getByText('Simulated input · no hardware reads')).toBeVisible();
  await page.getByRole('button', { name: 'Hold tag', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(page.getByText('New patient registered')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Remove tag', exact: true })).toBeVisible();
  await expect.poll(async () => page.locator('tbody tr').count(), { timeout: 6500, intervals: [5500] }).toBe(1);
  // A held tag must still be one arrival after more than five seconds.
  await page.waitForTimeout(5500);
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Remove tag', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ready for a scan' })).toBeVisible({ timeout: 5000 });
  const search = page.getByRole('textbox', { name: 'Search patients' });
  const firstName = (await page.locator('tbody tr .patient-cell strong').first().innerText()).split(' ')[0];
  await search.pressSequentially(firstName, { delay: 150 });
  await expect(search).toHaveValue(firstName);
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await expect(search).toBeFocused();
  await page.waitForTimeout(1200);
  await expect(search).toBeFocused();
  await search.fill('does not exist');
  await expect(page.getByText('No matching patients')).toBeVisible();
  await search.fill('');
  await page.locator('tbody tr').first().click();
  const drawer = page.getByRole('dialog');
  await expect(drawer.getByText('Raw scan count')).toBeVisible();
  await drawer.getByLabel('Care status').selectOption('In treatment');
  await expect(page.getByText('Patient care status updated.')).toBeVisible();
  await page.getByRole('button', { name: 'Close patient details' }).click();
  await page.getByRole('button', { name: 'Simulate scan', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(2);
  await expect(page.getByRole('heading', { name: 'Ready for a scan' })).toBeVisible({ timeout: 5000 });
  await page.reload();
  await expect(page.locator('tbody tr')).toHaveCount(2);
  const settingResponse = await page.request.post('/api/settings', { data: { absenceMs: 500 } });
  expect(settingResponse.ok()).toBeTruthy();
  for (let i = 3; i <= 15; i++) {
    await page.getByRole('button', { name: 'Simulate scan', exact: true }).click();
    await expect(page.locator('tbody tr')).toHaveCount(i);
    if (i < 15) await expect(page.getByRole('heading', { name: 'Ready for a scan' })).toBeVisible({ timeout: 5000 });
  }
  await expect(page.getByText('All 15 patient profiles are registered.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Simulate scan', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Dismiss arrival notification' }).click();
  await page.screenshot({ path: 'artifacts/dashboard-populated.png', fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export report' }).click();
  const download = await downloadPromise;
  await expect(download.suggestedFilename()).toMatch(/respondr-intake.*\.csv/);
  await page.getByRole('button', { name: 'Reset patient data', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(15);
  await page.getByRole('button', { name: 'Event history', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Event history.' })).toBeVisible();
  await expect(page.getByText('Scan & connection log')).toBeVisible();
  await page.getByRole('checkbox', { name: 'Include repeat reads' }).check();
  await expect(page.getByText('Duplicate suppressed').first()).toBeVisible();
  await page.getByRole('button', { name: 'Reader settings', exact: true }).click();
  await page.getByLabel('Tag absence threshold').fill('2.5');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(page.getByText('Scanner settings saved.')).toBeVisible();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('heading', { name: 'NIT J.' })).toBeVisible();
  const width = await page.evaluate(() => ({ viewport: window.innerWidth, document: document.documentElement.scrollWidth }));
  expect(width.document).toBeLessThanOrEqual(width.viewport);
  await page.screenshot({ path: 'artifacts/dashboard-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Reader settings', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Reader settings.' })).toBeVisible();
  await page.screenshot({ path: 'artifacts/settings-mobile.png', fullPage: true });
  const mobileSettingsWidth = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
  expect(mobileSettingsWidth.document).toBeLessThanOrEqual(mobileSettingsWidth.viewport);
  await page.locator('.reset-settings').getByRole('button', { name: 'Reset patient data', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: 'Reset patient data', exact: true }).click();
  await expect(page.getByText('Patient data cleared. Ready for the next intake.')).toBeVisible();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.getByText('Ready for the first arrival')).toBeVisible();
  await page.getByRole('button', { name: 'Simulate scan', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(1);
  expect(errors).toEqual([]);
});
